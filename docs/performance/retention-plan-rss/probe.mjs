import {readFile,writeFile,mkdtemp,rm} from 'node:fs/promises';
import {join} from 'node:path';
import {pathToFileURL} from 'node:url';
import {performance} from 'node:perf_hooks';
import {createHash} from 'node:crypto';
import v8 from 'node:v8';
import {session,freezeClock} from './helpers.mjs';
const [label,scaleText,fixturePath]=process.argv.slice(2);
const scale=Number(scaleText); freezeClock();
const directory=join(process.env.RSS_ROOT ?? "/tmp/dsh-rss-research",label,'lib');
const {EvolutionMemory}=await import(pathToFileURL(join(directory,'dockyard-domain/memory.js')));
let fixture=JSON.parse(await readFile(fixturePath,'utf8'));
const fixtureSha256=createHash('sha256').update(JSON.stringify(fixture)).digest('hex');
const temp=await mkdtemp('/tmp/dsh-rss-child-');
const memory=await session({EvolutionMemory},temp,fixture); fixture=null;
global.gc();
const before=process.memoryUsage(), maxBefore=process.resourceUsage().maxRSS*1024;
let ticks=0, peakHeap=before.heapUsed, peakRss=before.rss;
const samples=[];
const sample=kind=>{const u=process.memoryUsage(); peakHeap=Math.max(peakHeap,u.heapUsed);peakRss=Math.max(peakRss,u.rss);samples.push({kind,rss:u.rss,heapUsed:u.heapUsed});};
const timer=setInterval(()=>{ticks++;sample('timer');},2);
const start=performance.now();
const report=await memory.compact({dryRun:true});
const wallMs=performance.now()-start;
sample('endpoint'); clearInterval(timer);
const maxAfter=process.resourceUsage().maxRSS*1024;
const endpoint=process.memoryUsage();
global.gc();
const post=process.memoryUsage();
console.log(JSON.stringify({label,scale,flags:process.execArgv,fixtureSha256,before,maxBefore,maxAfter,maxDelta:maxAfter-maxBefore,post,endpoint,sampledHeapDelta:peakHeap-before.heapUsed,sampledRss:peakRss,ticks,samples,wallMs,heapLimit:v8.getHeapStatistics().heap_size_limit,report}));
await rm(temp,{recursive:true,force:true});
