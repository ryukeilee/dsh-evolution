export function reverseStagedElementMemoRound(file, source) {
  if (file !== "lib/domain-storage.js") return source;
  for (const [post, pre] of HUNKS) {
    assert.equal(source.split(post).length - 1, 1,
      `${file}: staged element memo reversal anchor must occur exactly once`);
    source = source.replace(post, pre);
  }
  return source;
}
